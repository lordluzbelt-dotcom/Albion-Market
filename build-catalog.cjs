const fs = require('node:fs');
const source = JSON.parse(fs.readFileSync('items-source.json', 'utf8').replace(/^\uFEFF/, ''));
const items = source.filter(x => /^T[4-8]_/.test(x.UniqueName) && x.LocalizedNames);
const catalog = items.map(x => [x.UniqueName, x.LocalizedNames['ES-ES'] || x.LocalizedNames['EN-US'], x.LocalizedNames['EN-US'] || '']);
fs.writeFileSync('assets/items.js', '/* Catalog: ao-data/ao-bin-dumps, retrieved ' + new Date().toISOString().slice(0,10) + '. Generated by build-catalog.cjs. */\nwindow.ALBION_ITEMS=' + JSON.stringify(catalog) + ';\n');
console.log(catalog.length + ' variantes guardadas');

